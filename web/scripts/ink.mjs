// Builds src/ink.gen.ts: every drawing in scripts/ink-art.mjs gone over with the hand-drawn brush
// (scripts/inkbrush.mjs), in the same line weight as the Open Peeps characters.
// Usage: node scripts/ink.mjs [--sheet out.svg]  (--sheet also writes a preview of everything)
import { writeFileSync } from 'node:fs';
import { brush, hash, rough } from './inkbrush.mjs';
import * as ART from './ink-art.mjs';

/** Line weight and decimals for each family (in its own units; all come out about 1.8 px on screen). */
const FAMILIES = {
  ICONS: { w: 2.1, dec: 2, ink: 'cur', shift: 0 },
  TAB_ICONS: { w: 2, dec: 2, ink: 'cur', shift: 0 },
  STICKERS: { w: 3, dec: 1, ink: 'ink', shift: 1 },
  PICTURES: { w: 3, dec: 1, ink: 'ink', shift: 1 },
  BIRD: { w: 2.8, dec: 1, ink: 'ink', shift: 0.8 },
  BITS: { w: 2, dec: 1, ink: 'cur', shift: 0 },
  CHEST: { w: 3.2, dec: 1, ink: 'ink', shift: 0 },
};

function draw(family, name, layers) {
  const F = FAMILIES[family];
  const out = [];
  layers.forEach((layer, i) => {
    const [kind, d, color, w] = layer;
    const seed = hash(`${family}:${name}:${i}`);
    if (kind === 'raw') return out.push(['raw', d]);
    if (kind === 'fill') return out.push([color, rough(d, F.w, seed, { dec: F.dec, amount: 0.08 })]);
    if (kind === 'ink') return out.push([F.ink, brush(d, w ?? F.w, seed, { dec: F.dec })]);
    if (kind === 'line') return out.push([color, brush(d, w ?? F.w, seed, { dec: F.dec, wobble: 0.12 })]);
    if (kind === 'shape') {
      out.push([color, rough(d, F.w, seed, { dec: F.dec, amount: 0.06, shift: color === 'cur' ? 0 : F.shift })]);
      out.push([color === 'cur' ? 'cur' : F.ink, brush(d, w ?? F.w, seed + 1, { dec: F.dec })]);
      return;
    }
    throw new Error(`${family}.${name}: unknown layer ${kind}`);
  });
  return out;
}

let ts = `// Generated by scripts/ink.mjs from scripts/ink-art.mjs. Do not edit.
// Each drawing is a list of [color, d]: a palette name, 'ink' (navy), 'cur' (currentColor) or
// 'duo' (a light wash of currentColor); 'raw' layers are SVG kept as they are (lettering).

export type InkLayer = readonly [string, string];
`;
// The hint pictures are only needed in lessons, so they get a file (and a chunk) of their own.
let pics = `// Generated by scripts/ink.mjs from scripts/ink-art.mjs. Do not edit.
import type { InkLayer } from './ink.gen';
`;
const sheet = [];
for (const family of Object.keys(FAMILIES)) {
  const drawings = Object.fromEntries(Object.entries(ART[family]).map(([name, layers]) => [name, draw(family, name, layers)]));
  const line = `\nexport const ${family}: Record<${Object.keys(drawings).map((k) => JSON.stringify(k)).join(' | ')}, readonly InkLayer[]> = ${JSON.stringify(drawings)};\n`;
  if (family === 'PICTURES') pics += line + `\n/** Pictures that are a sticker already. */\nexport const PICTURE_STICKERS = ${JSON.stringify(ART.PICTURE_STICKERS)} as const;\n`;
  else ts += line;
  sheet.push([family, drawings]);
}
writeFileSync(new URL('../src/pictures.gen.ts', import.meta.url), pics);
console.log(`pictures.gen.ts: ${(pics.length / 1024).toFixed(1)} KB`);
ts += `\nexport const SOLID_ICONS: readonly string[] = ${JSON.stringify(ART.SOLID_ICONS)};\n`;
writeFileSync(new URL('../src/ink.gen.ts', import.meta.url), ts);
console.log(`ink.gen.ts: ${(ts.length / 1024).toFixed(1)} KB`);

// A preview of every drawing, for checking by eye.
const at = process.argv.indexOf('--sheet');
if (at > 0) {
  const PAL = { blue: '#0164F9', deep: '#0142D8', sky: '#038CFB', skyLight: '#19B6FC', sun: '#FCC50E', orange: '#F8820C', navy: '#071334', slate: '#404D6B', cream: '#EFE7D0', red: '#E5303A', white: '#FFFFFF', ink: '#071334', cur: '#071334', duo: 'rgba(7,19,52,.2)' };
  const VB = { ICONS: 24, TAB_ICONS: 24, STICKERS: 64, PICTURES: 64, BIRD: 120, BITS: 24, CHEST: 80 };
  let y = 0, body = '';
  for (const [family, drawings] of sheet) {
    body += `<text x="4" y="${y + 14}" font-size="13" font-family="sans-serif" fill="#555">${family}</text>`;
    y += 20;
    let x = 0;
    for (const [name, layers] of Object.entries(drawings)) {
      if (x + 76 > 1216) { x = 0; y += 92; }
      const s = 64 / VB[family];
      body += `<g transform="translate(${x + 6} ${y}) scale(${s})">${family === 'BIRD' ? '' : ''}${layers.map(([c, d]) => (c === 'raw' ? d : `<path d="${d}" fill="${PAL[c] ?? c}"/>`)).join('')}</g>`;
      body += `<text x="${x + 38}" y="${y + 80}" font-size="9" text-anchor="middle" font-family="sans-serif" fill="#888">${name}</text>`;
      x += 76;
    }
    y += 96;
  }
  writeFileSync(process.argv[at + 1], `<svg xmlns="http://www.w3.org/2000/svg" width="1216" height="${y}" viewBox="0 0 1216 ${y}"><rect width="1216" height="${y}" fill="#fff"/>${body}</svg>`);
}
