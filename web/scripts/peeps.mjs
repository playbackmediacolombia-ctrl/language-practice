// Builds src/characters/peeps.gen.ts from Open Peeps by Pablo Stanley (CC0 1.0, via the
// @dicebear/open-peeps package): the bust, the hairstyles the role-play characters use, glasses,
// and faces taken apart into brows, eyes, nose and mouths so they can be rigged and animated.
// Colors become CSS variables, so each character is recolored in the app's palette.
// Usage: node scripts/peeps.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { shapes } from './svgparts.mjs';

const LIB = new URL('../node_modules/@dicebear/open-peeps/lib/', import.meta.url);
const load = async (file) => {
  // The drawings import only an XML-escape helper from @dicebear/core; it isn't needed here.
  const src = readFileSync(new URL(file, LIB), 'utf8').replace(/^import \{ escape \} from '@dicebear\/core';/m, 'const escape = { xml: (s) => s };');
  return import(`data:text/javascript;base64,${Buffer.from(src).toString('base64')}`);
};
const { head } = await load('components/head.js');
const { face } = await load('components/face.js');
const { accessories } = await load('components/accessories.js');
const index = readFileSync(new URL('index.js', LIB), 'utf8');

const SENTINELS = { skin: 'PEEPSKIN', clothing: 'PEEPCLOTH', headContrast: 'PEEPHAIR' };
const recolor = (svg) =>
  svg
    .replaceAll('PEEPSKIN', 'var(--peep-skin)')
    .replaceAll('PEEPCLOTH', 'var(--peep-cloth)')
    .replaceAll('PEEPHAIR', 'var(--peep-hair)')
    .replace(/fill="#000"/g, 'fill="var(--peep-ink)"')
    .replace(/fill="#fff"/gi, 'fill="var(--peep-white)"')
    .replace(/\s+/g, ' ');

// The bust (shoulders and neck): the first group of the avatar's body.
const body = recolor(index.match(/body: `(<g fill-rule[\s\S]*?<\/g>)<g transform="matrix/)[1].replace(/\$\{escape\.xml\(`\$\{colors\.(\w+)\}`\)\}/g, (_, c) => SENTINELS[c]));

const HEADS = ['pomp', 'bun', 'mediumBangs', 'grayShort', 'hijab', 'afro', 'grayBun', 'hatBeanie', 'longCurly', 'short2', 'twists2', 'bangs'];
const heads = Object.fromEntries(HEADS.map((h) => [h, recolor(head[h]({}, SENTINELS))]));
const glasses = { round: recolor(accessories.glasses2({}, SENTINELS)), square: recolor(accessories.glasses5({}, SENTINELS)) };

/** One shape of a face, plus any white or colored details (teeth, tongue) drawn inside it. */
function part(faceName, i) {
  const all = shapes(face[faceName]({}, SENTINELS));
  const main = all[i];
  const within = all.filter((s, j) => j !== i && s.fill !== '#000' && s.box.x0 >= main.box.x0 - 2 && s.box.x1 <= main.box.x1 + 2 && s.box.y0 >= main.box.y0 - 2 && s.box.y1 <= main.box.y1 + 2);
  const svg = [main, ...within].map((s) => `<path d="${s.d}" fill="${s.fill}" fill-rule="evenodd"/>`).join('');
  const b = main.box;
  return { svg: recolor(svg), box: [b.x0, b.y0, b.x1, b.y1].map((n) => Math.round(n)) };
}

const FACE = {
  nose: part('smile', 1),
  eyeL: part('smile', 2),
  eyeR: part('smile', 3),
  browL: part('smile', 4),
  browR: part('smile', 5),
  mouthRest: part('smile', 0),
  happyEyeL: part('calm', 2),
  happyEyeR: part('calm', 3),
  mouthSmile: part('calm', 0),
  joyEyeL: part('smileLOL', 6),
  joyEyeR: part('smileLOL', 7),
  joyBrowL: part('smileLOL', 4),
  joyBrowR: part('smileLOL', 5),
  mouthLaugh: part('smileLOL', 8),
  worryBrowL: part('concerned', 6),
  worryBrowR: part('concerned', 3),
  thinkBrowL: part('cheeky', 4),
  thinkBrowR: part('cheeky', 5),
  mouthO: part('cheeky', 0),
  mouthHmm: part('tired', 0),
};

const out = `// Generated by scripts/peeps.mjs from Open Peeps by Pablo Stanley (CC0 1.0). Do not edit.
// Colors are CSS variables (--peep-skin, --peep-cloth, --peep-hair, --peep-ink, --peep-white).

/** The bust, in a 704×704 box. */
export const BODY = ${JSON.stringify(body)};
/** Hairstyles (with the head), placed at matrix(.99789 0 0 1 156 62). */
export const HEADS = ${JSON.stringify(heads, null, 2)} as const;
export type HeadStyle = keyof typeof HEADS;
/** Glasses, placed at translate(203 303). */
export const GLASSES = ${JSON.stringify(glasses, null, 2)} as const;
/** Face parts, placed at translate(315 248); box is [x0, y0, x1, y1] in that space. */
export const FACE = ${JSON.stringify(FACE, null, 2)} as const;
`;
writeFileSync(new URL('../src/characters/peeps.gen.ts', import.meta.url), out);
console.log(`peeps.gen.ts: ${(out.length / 1024).toFixed(1)} KB`);
